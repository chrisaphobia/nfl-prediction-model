"""Score the model against simple benchmarks on seasons it never trained on.

Two evaluations:
1. Held-out season: train on 2016-2024, test on every 2025 game.
2. Walk-forward: for each season 2018-2025, train on all earlier seasons and test on that season.

Metrics: accuracy (picked the winner), Brier score (mean squared error of the
win probability, lower is better; always saying 50% scores 0.25), and log loss.

Run from the repo root:  python src/evaluate.py
Writes results/metrics.md.
"""
import os

import pandas as pd
from sklearn.metrics import accuracy_score, brier_score_loss, log_loss

from model import MARKET_FEATURES, TEAM_FEATURES, TEST_SEASON, TRAIN_START, fit, load, split

WALK_FORWARD_SEASONS = range(2018, 2026)


def predictions(games, test_season):
    """Home-win probabilities for every game in test_season, from each method."""
    train, test = split(games, test_season)
    return test, {
        'Always pick home team': pd.Series(train['home_win'].mean(), index=test.index),
        'Betting favorite': test['market_home_prob'],
        'Elo (self-computed)': test['elo_home_prob'],
        'Logistic, no betting line': pd.Series(fit(train, TEAM_FEATURES).predict_proba(test[TEAM_FEATURES])[:, 1], index=test.index),
        'Logistic, with spread': pd.Series(fit(train, MARKET_FEATURES).predict_proba(test[MARKET_FEATURES])[:, 1], index=test.index),
    }


def score(y, p):
    p = p.clip(1e-6, 1 - 1e-6)
    return {'Accuracy': accuracy_score(y, p > 0.5), 'Brier': brier_score_loss(y, p), 'Log loss': log_loss(y, p, labels=[0, 1])}


def table(rows):
    df = pd.DataFrame(rows).T
    out = df.copy()
    out['Accuracy'] = df['Accuracy'].map('{:.1%}'.format)
    out['Brier'] = df['Brier'].map('{:.4f}'.format)
    out['Log loss'] = df['Log loss'].map('{:.4f}'.format)
    return out


def to_markdown(df):
    lines = ['| Method | ' + ' | '.join(str(c) for c in df.columns) + ' |', '|---|' + '---:|' * len(df.columns)]
    lines += [f'| {name} | ' + ' | '.join(str(v) for v in row) + ' |' for name, row in df.iterrows()]
    return '\n'.join(lines)


def main():
    games = load()

    # 1. Single held-out season
    test, preds = predictions(games, TEST_SEASON)
    holdout = table({name: score(test['home_win'], p) for name, p in preds.items()})

    # 2. Walk-forward: pool every test season's predictions, then score once
    pooled_y, pooled = [], {}
    per_season = {}
    for season in WALK_FORWARD_SEASONS:
        t, p = predictions(games, season)
        pooled_y.append(t['home_win'])
        for name, probs in p.items():
            pooled.setdefault(name, []).append(probs)
        per_season[season] = {name: accuracy_score(t['home_win'], probs > 0.5) for name, probs in p.items()}
    y_all = pd.concat(pooled_y)
    walk = table({name: score(y_all, pd.concat(ps)) for name, ps in pooled.items()})
    by_season = pd.DataFrame(per_season).map('{:.1%}'.format)

    train_n = len(split(games, TEST_SEASON)[0])
    report = '\n\n'.join([
        '# Evaluation results',
        f'Generated by `python src/evaluate.py`. Ties are excluded.',
        f'## Held-out season: train {TRAIN_START}-{TEST_SEASON - 1} ({train_n} games), test {TEST_SEASON} ({len(test)} games, incl. playoffs)',
        to_markdown(holdout),
        f'## Walk-forward {min(WALK_FORWARD_SEASONS)}-{max(WALK_FORWARD_SEASONS)} ({len(y_all)} games)',
        'Each season is predicted by a model trained only on the seasons before it.',
        to_markdown(walk),
        '### Accuracy by test season',
        to_markdown(by_season),
    ]) + '\n'

    os.makedirs('results', exist_ok=True)
    with open('results/metrics.md', 'w') as f:
        f.write(report)
    print(report)


if __name__ == '__main__':
    main()
